import { flushPromises, mount } from '@vue/test-utils'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import Fields from '../MonitorFallbackFields.vue'
import Routes from '../MonitorFallbackRoutes.vue'
const { getAll, get } = vi.hoisted(() => ({ getAll: vi.fn(), get: vi.fn() }))
vi.mock('@/api/admin', () => ({ adminAPI: { groups: { getAll } } }))
vi.mock('@/api/client', () => ({ apiClient: { get } }))
vi.mock('vue-i18n', () => ({ useI18n: () => ({ t: (key: string) => key }) }))
const group = (id: number, extra = {}) => ({ id, name: 'G' + id, status: 'active', platform: 'openai', group_type: 'business', rate_multiplier: 0.35, subscription_type: 'standard', ...extra })
beforeEach(() => { getAll.mockResolvedValue([group(1), group(2), group(3, { platform: 'gemini' }), group(4, { group_type: 'fallback' }), group(5, { status: 'inactive' })]); get.mockResolvedValue({ data: [] }) })
afterEach(() => { vi.clearAllMocks(); vi.useRealTimers() })
describe('Monitored fallback fields', () => {
 it('loads candidates only when fallback is selected and caches an empty result', async () => {
  getAll.mockResolvedValue([])
  const wrapper = mount(Fields, { props: { groupType: 'business', groupIds: [], platform: 'openai' } })
  await flushPromises()
  expect(getAll).not.toHaveBeenCalled()
  await wrapper.setProps({ groupType: 'fallback' })
  await flushPromises()
  expect(getAll).toHaveBeenCalledOnce()
  await wrapper.setProps({ groupType: 'business' })
  await wrapper.setProps({ groupType: 'fallback' })
  await flushPromises()
  expect(getAll).toHaveBeenCalledOnce()
  wrapper.unmount()
 })
 it('preserves hydrated chains when opening a different platform editor', async () => {
  const wrapper = mount(Fields, { props: { groupType: 'fallback', groupIds: [1], platform: 'openai' } })
  await flushPromises()
  await wrapper.setProps({ platform: 'gemini', groupIds: [3], currentId: 10 })
  expect(wrapper.emitted('update:groupIds')).toBeUndefined()
  expect(wrapper.findAll('li')[0]!.text()).toContain('G3')
  await wrapper.setProps({ platform: 'openai' })
  expect(wrapper.emitted('update:groupIds')?.at(-1)).toEqual([[]])
  wrapper.unmount()
 })
 it('loads all active groups independent of the current table page and preserves priority', async () => {
  const wrapper = mount(Fields, { props: { groupType: 'fallback', groupIds: [2, 1], platform: 'openai' } })
  await flushPromises()
  expect(getAll).toHaveBeenCalledOnce()
  expect(wrapper.findAll('li').map(li => li.text())).toEqual([expect.stringContaining('1. G2'), expect.stringContaining('2. G1')])
  const options = wrapper.findAll('select')[1]!.findAll('option').map(o => o.attributes('value'))
  expect(options).toEqual(['', '1', '2'])
  await wrapper.findAll('li')[1]!.findAll('button')[0]!.trigger('click')
  expect(wrapper.emitted('update:groupIds')?.at(-1)).toEqual([[1, 2]])
  await wrapper.get('select').setValue('business')
  expect(wrapper.emitted('update:groupIds')?.at(-1)).toEqual([[]])
  wrapper.unmount()
 })
 it('adds and removes targets and keeps the route chain empty for business', async () => {
  const wrapper = mount(Fields, { props: { groupType: 'fallback', groupIds: [1], platform: 'openai' } })
  await flushPromises()
  await wrapper.findAll('select')[1]!.setValue('2')
  expect(wrapper.emitted('update:groupIds')?.at(-1)).toEqual([[1, 2]])
  await wrapper.findAll('li')[0]!.findAll('button')[2]!.trigger('click')
  expect(wrapper.emitted('update:groupIds')?.at(-1)).toEqual([[]])
  wrapper.unmount()
 })
})
describe('Monitored fallback status', () => {
 it('uses user-scoped routes without showing the private candidate chain', async () => {
  get.mockResolvedValue({ data: [{ entry_group_id: 10, entry_group_name: 'Fallback', target_group_id: 2, target_group_name: 'B', candidates: null }] })
  const wrapper = mount(Routes, { props: { audience: 'user' } }); await flushPromises()
  expect(get).toHaveBeenCalledWith('/channel-monitors/fallback-routes', { params: { model: undefined } })
  expect(wrapper.text()).toContain('→ B')
  wrapper.unmount()
 })
 it('shows the actual selected group and failed predecessors', async () => {
  get.mockResolvedValue({ data: [{ entry_group_id: 10, entry_group_name: 'Fallback', target_group_id: 2, target_group_name: 'B', candidates: [{ group_id: 1, group_name: 'A', status: 'failed', reason: 'monitor_failed' }, { group_id: 2, group_name: 'B', status: 'operational', reason: 'selected' }] }] })
  const wrapper = mount(Routes)
  await flushPromises()
  expect(wrapper.text()).toContain('Fallback')
  expect(wrapper.text()).toContain('→ B')
  expect(wrapper.text()).toContain('A: failed')
  await wrapper.get('input').setValue('test-model')
  await wrapper.get('button').trigger('click'); await flushPromises()
  expect(get).toHaveBeenLastCalledWith('/admin/groups/fallback-routes', { params: { model: 'test-model' } })
  wrapper.unmount()
 })
 it('reports exhausted chains and cancels polling on unmount', async () => {
  vi.useFakeTimers()
  get.mockResolvedValue({ data: [{ entry_group_id: 10, entry_group_name: 'Fallback', target_group_id: null, target_group_name: '', candidates: [] }] })
  const wrapper = mount(Routes); await flushPromises()
  expect(wrapper.text()).toContain('admin.groups.monitorFallback.unavailable')
  wrapper.unmount(); await vi.advanceTimersByTimeAsync(30000)
  expect(get).toHaveBeenCalledOnce()
 })
})
